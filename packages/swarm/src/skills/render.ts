import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { PartyConfig } from '../config/load.ts'

export const generatedMarker = '<!-- generated by swarm skills sync; edits are overwritten -->'

const frontmatterBlock = /^---\r?\n(?:[^\n]*\n)*?---(\r?\n|$)/
const templates = new URL('../../skills', import.meta.url)
const paths = [
  'mob-creation/SKILL.md',
  'mob-creation/brief-template.md',
  'spawner/SKILL.md',
  'mob/SKILL.md',
  'research/SKILL.md',
  'reviewer/SKILL.md',
  'policy/SKILL.md',
]

function lookup(config: unknown, path: string): unknown {
  let value = config
  for (const key of path.split('.')) {
    if (value === null || typeof value !== 'object' || !Object.hasOwn(value, key)) {
      throw new Error(`missing template value: ${path}`)
    }
    value = (value as Record<string, unknown>)[key]
  }
  return value
}

export function renderTemplate(template: string, config: unknown): string {
  return template.replace(
    /<<[^\n]*?>>|\{\{\s*(?:(join|yesno)\s+)?([\w-]+(?:\.[\w-]+)*)\s*\}\}/g,
    (match: string, operation: string | undefined, path: string | undefined) => {
      if (path === undefined) return match
      const value = lookup(config, path)
      if (operation === 'join') {
        if (Array.isArray(value)) return value.join(', ')
        throw new Error(`expected array at ${path}`)
      }
      if (operation === 'yesno') {
        if (typeof value === 'boolean') return value ? 'yes' : 'no'
        throw new Error(`expected boolean at ${path}`)
      }
      if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') {
        return String(value)
      }
      throw new Error(`expected scalar at ${path}`)
    },
  )
}

export function isGeneratedText(text: string): boolean {
  const frontmatter = text.match(frontmatterBlock)
  return text.slice(frontmatter?.[0].length ?? 0).split(/\r?\n/, 1)[0] === generatedMarker
}

export function hasBlockedReference(text: string): boolean {
  if (/tigeryard/i.test(text)) return true
  if (/&#(?:[0-9]+|[xX][0-9a-fA-F]+)/.test(text)) return true
  for (const [encoded] of text.matchAll(/%[0-9a-fA-F]{2}/g)) {
    if (/[A-Za-z]/.test(String.fromCharCode(Number.parseInt(encoded.slice(1), 16)))) return true
  }
  return false
}

export function renderSkills(config: PartyConfig): Map<string, string> {
  const files = new Map<string, string>()
  let startupChars = 0
  for (const path of paths) {
    const template = readFileSync(join(fileURLToPath(templates), path), 'utf8')
    const text = renderTemplate(template, config)
    if (hasBlockedReference(text)) throw new Error(`blocked reference in ${path}`)
    const frontmatter = text.match(frontmatterBlock)
    const newline = frontmatter?.[1] || '\n'
    const prefix = frontmatter ? frontmatter[0] + (frontmatter[1] ? '' : newline) : ''
    const marked = `${prefix}${generatedMarker}${newline}${text.slice(frontmatter?.[0].length ?? 0)}`
    files.set(path, marked)
    if (path.endsWith('/SKILL.md')) startupChars += marked.length
  }
  const tokens = Math.ceil(startupChars / 4)
  if (tokens >= 4000) throw new Error(`startup text is ${tokens} tokens, must be under 4000 tokens`)
  return files
}
